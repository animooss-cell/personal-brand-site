export function aiTrainingAhvazMarkdown(courses: { title: string; slug: string; audience: string | null; description: string | null }[]) {
  const c = aiTrainingAhvaz;
  return mdJoin([
    mdHeading(1, c.hero.title),
    c.hero.lead,
    mdHeading(2, c.why.heading),
    c.why.text,
    mdHeading(2, c.coursesHeading),
    courses.length
      ? mdList(
          courses.map(
            (course) =>
              `${mdLink(course.title, `/services/courses/${course.slug}`)}${course.audience ? ` (${course.audience})` : ""}${course.description ? `: ${course.description}` : ""}`,
          ),
        )
      : "هنوز دوره‌ای منتشر نشده است.",
    mdHeading(2, c.curriculumHeading),
    mdList(c.curriculum),
    mdHeading(2, c.fit.heading),
    c.fit.text,
    mdList(c.tracks.map((t) => `**${t.title}:** ${t.desc}`)),
    mdHeading(2, c.notFit.heading),
    c.notFit.text,
    mdHeading(2, c.versus.heading),
    ...c.versus.paragraphs,
    mdHeading(2, c.stepsHeading),
    mdList(c.steps.map((s) => `**${s.title}:** ${s.desc}`), true),
    mdHeading(2, c.deliverablesHeading),
    mdList(c.deliverables),
    mdHeading(2, c.pricing.heading),
    c.pricing.text,
    mdHeading(2, c.format.heading),
    richToMarkdown(c.format.text),
    mdHeading(2, c.collaborationsHeading),
    mdList(c.collaborations),
    mdHeading(2, ENTITY_BIO_HEADING),
    `${ENTITY_BIO_FA} ${mdLink("بیشتر درباره‌ی من", "/about")}`,
    mdHeading(2, "مقالات مرتبط"),
    mdList(c.relatedArticles.map((a) => mdLink(a.label, a.href))),
    mdHeading(2, "سوالات متداول"),
    mdFaq(c.faqs),
    richToMarkdown(c.related),
    mdHeading(2, c.cta.heading),
    `${c.cta.text} — ${mdLink(c.cta.button, "/contact")}`,
  ]);
}
